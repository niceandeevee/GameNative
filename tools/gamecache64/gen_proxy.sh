#!/bin/sh
# Generates the powrprof.dll proxy glue from powrprof.exports (one export name per line):
#   proxy_stubs.S   one `jmp *slot(%rip)` per export, so arguments and return values pass through untouched
#   proxy_names.h   the export names, in slot order, for proxy_init() to resolve
#   gamecache.def   exports each name from its stub
set -e
cd "$(dirname "$0")"
n=0
{
    echo "/* Generated by gen_proxy.sh from powrprof.exports. */"
    echo "    .text"
    while read -r name; do
        [ -n "$name" ] || continue
        echo "    .globl stub_$name"
        echo "stub_$name: jmp *proxy_slots+$((n * 8))(%rip)"
        n=$((n + 1))
    done < powrprof.exports
    echo "    .data"
    echo "    .globl proxy_slots"
    echo "    .p2align 3"
    echo "proxy_slots: .zero $((n * 8))"
} > proxy_stubs.S
{
    echo "/* Generated by gen_proxy.sh from powrprof.exports. */"
    sed '/^$/d; s/.*/    "&",/' powrprof.exports
} > proxy_names.h
{
    echo "; Generated by gen_proxy.sh from powrprof.exports: every export jumps to the same function of"
    echo "; Wine's own powrprof.dll (proxy.c)."
    echo "LIBRARY powrprof.dll"
    echo "EXPORTS"
    sed '/^$/d; s/.*/    & = stub_&/' powrprof.exports
} > gamecache.def
